# Calculates entropy. Says what it does right on the tin. Counts the instances
# of values within the data, and divides it by the length of the data to get the
# probability of the values, then hits it with the sum(p * log2(p)).
def calculate_entropy(data):
    counts = data.value_counts()
    probabilities = counts / len(data)
    probabilities = probabilities[probabilities > 0]  # Filter out zero probabilities
    entropy = -np.sum(probabilities * np.log2(probabilities))
    return entropy


# Information Gain. Takes the entropy of an attribute and the entropy of the
# entire column and divides them to get the weight of that attribute. Multiply
# by the weight to get weighted entropy, subtract from overall entropy, and
# you've got a result!
def calculate_information_gain(df, target_column, predictor_column):
    # Calculate overall entropy
    overall_entropy = calculate_entropy(df[target_column])

    # Calculate weighted entropy for splits
    weighted_entropy = 0
    for category in df[predictor_column].unique():
        subset = df[df[predictor_column] == category]
        subset_entropy = calculate_entropy(subset[target_column])
        weight = len(subset) / len(df)
        weighted_entropy += weight * subset_entropy

    # Information gain is the reduction in entropy
    information_gain = overall_entropy - weighted_entropy
    return information_gain

# Super simple function to determine best splits based on entropy and info gain.
# We loop through the columns (making sure the column actually exists in the
# DataFrame, because we might have trimmed it when we discretized the data),
# and calculate the info gain on that column. If it's the best info gain, then
# we return that column and gain value.
def find_best_split(df, target_column, predictor_columns):
    best_gain = 0
    best_column = None

    for column in predictor_columns:
        if column not in df.columns:  # Ensure column exists
            print(f"Warning: {column} does not exist in DataFrame, skipping.")
            continue

        gain = calculate_information_gain(df, target_column, column)
        if gain > best_gain:
            best_gain = gain
            best_column = column

    return best_column, best_gain

# Building the trees! This is the meat and potatoes of the whole thing.
# We pass in a max_depth, because the tree becomes pretty unweildy after 5
# layers. I started with 3, and that went well, but 5 upped accuracy by about
# 10% overall, and only added about 2 minutes to the runtime.
def build_tree(df, target_column, predictor_columns, depth=0, max_depth=5):

    #If we reach our max depth, or if we find a node, make a leaf!
    if depth >= max_depth or len(df[target_column].unique()) == 1:

        # This just counts the number of unique values. Normalizing it divides
        # the count by the number of rows to produce a percentage
        counts = df[target_column].value_counts(normalize=True)
        majority_class = counts.idxmax()  # Most frequent index (bin label)
        confidence = counts.max()  # Proportion of majority class (value)
        leaf = {"Prediction": majority_class, "Confidence": confidence}
        #print(f"Leaf Node Created: {leaf}")  # Debugging print

        # Return the leaf, which is a dict of a bin label, and a confidence
        return leaf

    best_column, best_gain = find_best_split(df, target_column, predictor_columns)

    # If we can't find anymore splits to make, then we're probably done with
    # this branch, so we should return what we have.
    if not best_column or best_gain == 0:
        counts = df[target_column].value_counts(normalize=True)
        majority_class = counts.idxmax()
        confidence = counts.max()
        leaf = {"Prediction": majority_class, "Confidence": confidence}
        #print(f"Leaf Node Created (No Split): {leaf}")  # Debugging print
        return leaf

# Trees do like recursion. Here, we're initializing what the split attribute
# will be. We then loop though each of the bin labels for each column (High,
# Medium and Low), and create a subset of the data, based on when the value
# of the current bin label is equal to the value of the best column. We need
# to do this to make sure the next tree we build will be using a subset of the
# data, instead of... all of it. Which would be not useful.
    tree = {best_column: {}}
    for category in df[best_column].unique():
        subset = df[df[best_column] == category]
        # We then recurse back up, with the new subset of data, and increased
        # depth
        tree[best_column][category] = build_tree(
            subset, target_column, predictor_columns, depth + 1, max_depth
        )

    return tree

#--------Construct Predictions Logic-----------

def predict_with_confidence(tree, row):
    # Check if current tree is a leaf node
    # The trees are stored as dictionaries, with prediction and confidence in the
    # leaf nodes. If it doesn't have those values in the node, then we don't have
    # the ability to predict anything yet!
    # Also, if I didn't check for is tree a dict, it would fail on the branches
    # when trying to evaluate them, so I need to add that check on both cases.
    if isinstance(tree, dict) and "Prediction" in tree and "Confidence" in tree:
        return tree["Prediction"], tree["Confidence"]

    # Otherwise, process branch nodes
    if isinstance(tree, dict):
        root = next(iter(tree))  # Get the feature to split on
        value = row.get(root, None)  # Fetch the feature value from the row
        subtree = tree[root].get(value, None)  # Navigate to the correct branch

        # Depending on the data splits we have cases where there isn't an instance
        # of a particular attribute having a certain value, so we have no way
        # to predict what to do with it. In that case, we just return it as a
        # 0 confidence prediction of nothing instead of failing horribly.
        if subtree is None:
            print(f"Missing branch for value '{value}' in feature '{root}'")  # Debugging print
            return None, 0  # Handle missing branches gracefully

        # Recurse to the next branch to evaluate it!
        return predict_with_confidence(subtree, row)

    # If the tree doesn't match expected structures, handle as invalid
    # I haven't seen this happen lately, but just in case I figured it wouldn't
    # be a bad idea to have some security. If a bad structure comes along,
    # return it as a 0 confidence prediction of nothing!
    print(f"Invalid tree structure encountered: {tree}")  # Debugging print
    return None, 0

#---------Testing and Validation-----------#

# Split data into training, testing and validation sets. Current split is
# 30% of data going to testing and validation, 50% of that (15% total) going to
# validation, which leaves 70% data for training the tree.

def split_data(df, target_column, test_size=0.3, validation_size=0.5):

    # Split into training and temp (testing + validation)
    # random_state value ensure random split is seeded with a constant for
    # reproducability. We can omit that for a more random split result
    train_df, temp_df = train_test_split(df, test_size=test_size, random_state=1)

    # Split temp into testing and validation
    test_df, val_df = train_test_split(temp_df, test_size=validation_size, random_state=1)

    return train_df, test_df, val_df

def evaluate_single_tree(decision_tree, df, output_column, actual_columns):
    print(f"Evaluating predictions for: {output_column}")

    # Generate predictions
    # Had to learn about lambda and apply() here. lambda specifies an inline function
    # apply() will do that lambda function to either columns or rows of the
    # DataFrame. axis=1 means it specifies rows, and the row keyword after
    # lambda is a variable declaration. Basically, for each row in the DataFrame
    # pass in the decision tree and the current row into the predict function
    predictions = df.apply(lambda row: predict_with_confidence(decision_tree, row), axis=1)

    # Compile results
    # Make a copy of the output column we're evaluating predictions against
    result_df = df[[f"{output_column}_Discrete"]].copy()
    # Run through each item in the predictions array we just constructed and grab
    # the prediction values ("low", "medium", etc...)
    result_df['Predicted'] = predictions.apply(lambda x: x[0])
    # Do the same as above, but with the confidence scores of the predictions
    result_df['Confidence'] = predictions.apply(lambda x: x[1])

    # Add predictor columns
    # This will append the predictor columns related to our predictions
    # into the DataFrame. We don't technically need them, but it provides a
    # trace into why we predicted what we did
    for predictor in [f"{col}_Discrete" for col in actual_columns]:
        result_df[predictor] = df[predictor]

    return result_df

def calculate_accuracy(result_df, target_column):
    # Here we're comparing our predicted result with our output column value
    # If they are equal, it returns 1, which is summed so get a running count of
    # how many predictions were correct
    correct_predictions = (result_df[target_column] == result_df['Predicted']).sum()
    total_predictions = len(result_df)
    # We return the total of correct predictions divided by total predictions
    # to get the percentage accuracy for the output predictions.
    return correct_predictions / total_predictions

