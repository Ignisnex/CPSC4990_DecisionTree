#------Discretize Data----------
# Since we don't have a great handle on the data (other than the description)
# we'll rely on a quartile discretization approach, which can be
# applied to all predictor and output columns

def discretize_columns(df, columns):
    final_columns = []  # Successfully discretized columns

    # This was an issue I kept running into. One specific column that will be
    # named and shamed ('Machine5.Temperature3.C.Actual') doesn't have enough
    # variance to be binned properly, so it gums up everything else it touches.
    # It's my problem column, and I basically trim it.
    problem_columns = []

    # Define bin edges based on quartiles
    for column in columns:
        bins = [
            df[column].min(),  # Minimum value
            df[column].quantile(0.25),  # 25th percentile
            df[column].quantile(0.75),  # 75th percentile
            df[column].max()  # Maximum value
        ]

        # Ensure bins edges are unique to avoid errors. If I don't do this, then
        # Python dies and says it can't bin things with overlapping bin edges.
        unique_bins = sorted(set(bins))

        if len(unique_bins) > 2:  # Ensure at least 3 bins for meaningful categories
            labels = ['Low', 'Medium', 'High']  # These seemed as good of labels as any
            discrete_column = f"{column}_Discrete"

            # This is a handy little function that is used to bin data! Thanks
            # pandas, you make this project possible. We want to make new
            # columns so we can still reference the raw data if we need to, or
            # the discretized version, so we'll name it {column}_Discrete.
            # This function takes the DataFrame column we want to bin, what the
            # bin edges are (defined above), what the labels for those bins are
            # (the labels need to be the number of bin edges - 1), and a setting
            # to include either the lowest or highest value as a bin edge. I
            # went with lowest
            df[discrete_column] = pd.cut(
                df[column], bins=unique_bins, labels=labels[:len(unique_bins) - 1], include_lowest=True
            )
            final_columns.append(column)
        else:
            problem_columns.append(column)

    return final_columns, problem_columns

