# Be careful, this file is like 450MB, but does show what the tree looks like
# if you're brave enough, because it sucks to read
def summarize_predictions_all_trees_to_file(decision_trees, df, stage1_columns, actual_columns, filename="tree_predictions.txt"):
    with open(filename, "w") as f:
        for output_column in stage1_columns:
            f.write(f"\nPredictions for {output_column}:\n")

            # Ensure the tree exists
            tree = decision_trees.get(output_column)
            if not tree:
                f.write(f"Warning: No tree found for {output_column}, skipping.\n")
                continue

            # Generate predictions
            predictions = df.apply(lambda row: predict_with_confidence(tree, row), axis=1)

            # Compile results
            result_df = df[[f"{output_column}_Discrete"]].copy()
            result_df['Predicted'] = predictions.apply(lambda x: x[0])
            result_df['Confidence'] = predictions.apply(lambda x: x[1])

            # Include predictor values for readability
            for predictor in [f"{col}_Discrete" for col in actual_columns]:
                result_df[predictor] = df[predictor]

            # Group predictions by predicted output
            for predicted_value in result_df['Predicted'].unique():
                f.write(f"Output -> {predicted_value}:\n")

                # Filter rows where the prediction matches this category
                subset = result_df[result_df['Predicted'] == predicted_value]

                # Extract predictor values per output
                for _, row in subset.iterrows():
                    predictor_values = [f"{col} = {row[col]}" for col in result_df.columns if col not in ['Predicted', 'Confidence', f"{output_column}_Discrete"]]
                    f.write(f"  - {', '.join(predictor_values)}\n")
                f.write("\n")  # Blank line for spacing
    print(f"\nPredictions saved to {filename}")

